"""标识符工具 —— 与业务无关的 id 处理，谁都能用、不牵扯任何场景。"""

from uuid import UUID


def short_id(entity_id: UUID) -> str:
    """取 UUID 的短标识 —— **必须取后 8 位，不能取前 8 位**。

    本项目的 id 是 UUIDv7：前 48 位是毫秒时间戳，后 74 位才是随机数。
    `hex[:8]` 取到的是时间戳的高 32 位，**每 65 秒才变一次** —— 同一分钟内
    创建的两个实体，短标识必然相同。这不是小概率碰撞，是必然碰撞：
    手点招募两个成员、脚本批量建 agent，都会撞上。

    撞了不会报错，而是**静默串台**：派活按这个键找人，两个成员同键就会
    派给错的那个（2026-08-03 实际发生过：管家说派给资料员，活却落到了
    制图员手上，而制图员没挂知识库，只能在沙箱里空翻一气）。

    取后 8 位落在随机段，碰撞概率约 1/2^32，且与创建时间无关。
    """
    return entity_id.hex[-8:]
